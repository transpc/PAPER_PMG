      SUBROUTINE opr1000_coolant_transient_user
!      
      USE Zb_condition , ONLY: rhob_liq,rhob_gas,   &
                               p_fb,tb_gas,tb_liq,  &
                               qualab,eb_liq,eb_gas      
      USE Zncg         , ONLY: tao,cvao_nvin,uao_nvin,dcva_nvin,ra_nvin,qn_cell
      USE Ztimecon     , ONLY: time
      USE Zcore        , ONLY: myrank
      USE Zio_unit     , ONLY: unit_log
      
!      
      IMPLICIT NONE
!
      REAL(8) tmp1,tmp2,time_trans
      REAL(8) tin1,tin2
      REAL(8) tcoo1,tcoo2     
      REAL(8), SAVE::time_tco
!      
      LOGICAL, SAVE::init_tco      
      DATA init_tco/.TRUE./
!      
      !Initiation
      IF(init_tco)then
         IF(myrank.eq.0)write(*,*)  '====================================================='
         IF(myrank.eq.0)write(*,*)  ' START to inject cold coolant at ',time,' sec'
         IF(myrank.eq.0)write(*,*)  '====================================================='
         IF(myrank.eq.0)WRITE(unit_log,*)'====================================================='
         IF(myrank.eq.0)WRITE(unit_log,*)' START to inject cold coolant at ',time,' sec'
         IF(myrank.eq.0)WRITE(unit_log,*)'====================================================='
         time_tco=time
         init_tco=.false. 
      ENDIF
      time_trans=time-time_tco
      !Injection'
      IF(.not.init_tco .and. time_trans.ge.0.0d0 .and. time_trans.lt.60.0d0)then
         tcoo1=tin1(time-time_tco)
         tb_liq(1)=tcoo1
         tb_gas(1)=tcoo1

         CALL convert_temp2erg(p_fb(1),tb_liq(1),tb_gas(1),qualab(1),&
                               eb_liq(1),eb_gas(1),rhob_liq(1),rhob_gas(1),&
                               tmp1,tmp2,tao,cvao_nvin(1),uao_nvin(1),dcva_nvin(1),ra_nvin(1),qn_cell(1,:))
         tb_liq(2)=tcoo1
         tb_gas(2)=tcoo1
         CALL convert_temp2erg(p_fb(2),tb_liq(2),tb_gas(2),qualab(2),&
                               eb_liq(2),eb_gas(2),rhob_liq(2),rhob_gas(2),&
                               tmp1,tmp2,tao,cvao_nvin(2),uao_nvin(2),dcva_nvin(2),ra_nvin(2),qn_cell(2,:))


         tcoo2=tin2(time-time_tco)
         tb_liq(3)=tcoo2
         tb_gas(3)=tcoo2
         CALL convert_temp2erg(p_fb(3),tb_liq(3),tb_gas(3),qualab(3),&
                               eb_liq(3),eb_gas(3),rhob_liq(3),rhob_gas(3),&
                               tmp1,tmp2,tao,cvao_nvin(3),uao_nvin(3),dcva_nvin(3),ra_nvin(3),qn_cell(3,:))
         tb_liq(4)=tcoo2
         tb_gas(4)=tcoo2
         CALL convert_temp2erg(p_fb(4),tb_liq(4),tb_gas(4),qualab(4),&
                               eb_liq(4),eb_gas(4),rhob_liq(4),rhob_gas(4),&
                               tmp1,tmp2,tao,cvao_nvin(4),uao_nvin(4),dcva_nvin(4),ra_nvin(4),qn_cell(4,:))
      ENDIF
